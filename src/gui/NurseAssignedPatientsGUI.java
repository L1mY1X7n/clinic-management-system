    private void loadAssignedPatients() {
        ArrayList<String[]> rows = new ArrayList<>();
        File file = new File(APPOINTMENTS_FILE);


        if (!file.exists()) {
            JOptionPane.showMessageDialog(this, "appointments.txt not found.", "File Missing", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try (BufferedReader reader = new BufferedReader(new FileReader(file))) {
            String line;
            while ((line = reader.readLine()) != null) {
                if (line.trim().isEmpty()) continue;
                String[] parts = line.split(",", -1);
                if (parts.length == 8 && parts[3].equalsIgnoreCase(loggedInNurseId)) {
                    rows.add(new String[]{parts[0], parts[1], parts[2], parts[4], parts[7]});
                }
            }
        } catch (IOException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "Error reading appointments.txt", "Error", JOptionPane.ERROR_MESSAGE);
        }

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        for (String[] row : rows) {
            model.addRow(row);
        }

        if (rows.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No patients are currently assigned to you.",
                "No Patients", JOptionPane.INFORMATION_MESSAGE);
        }
    }

