    private ArrayList<String> readLines() {
        ArrayList<String> lines = new ArrayList<>();
        File file = new File(FILE_NAME);
        if (!file.exists()) return lines;
        try (BufferedReader br = new BufferedReader(new FileReader(file))) {
            String line;
            while ((line = br.readLine()) != null) {
                if (!line.trim().isEmpty()) lines.add(line);
            }
        } catch (IOException e) {
            logger.log(java.util.logging.Level.SEVERE, "Error reading " + FILE_NAME, e);
        }
        return lines;
    }

    private void writeLines(ArrayList<String> lines) {
        try (BufferedWriter bw = new BufferedWriter(new FileWriter(FILE_NAME))) {
            for (String line : lines) {
                bw.write(line);
                bw.newLine();
            }
        } catch (IOException e) {
            logger.log(java.util.logging.Level.SEVERE, "Error writing " + FILE_NAME, e);
        }
    }

    private String nextRecordId(ArrayList<String> lines) {
        int max = 0;
        for (String line : lines) {
            String[] parts = line.split(",");
            try {
                int id = Integer.parseInt(parts[0].trim());
                if (id > max) max = id;
            } catch (NumberFormatException e) {
         
            }
        }
        return String.valueOf(max + 1);
    }
    private void updateOrCreateRecord(String patientId, String temperature, String bloodPressure, String heartRate, String notes) {
        ArrayList<String> lines = readLines();
        ArrayList<String> newLines = new ArrayList<>();
        boolean found = false;

        for (String line : lines) {
            String[] parts = line.split(",", -1);
            if (parts.length >= 6 && parts[1].trim().equalsIgnoreCase(patientId)) {
                parts[2] = temperature;
                parts[3] = bloodPressure;
                parts[4] = heartRate;
                parts[5] = notes;
                newLines.add(String.join(",", parts));
                found = true;
            } else {
                newLines.add(line);
            }
        }

        if (!found) {
            String newId = nextRecordId(lines);
            newLines.add(String.join(",", newId, patientId, temperature, bloodPressure, heartRate, notes));
        }

        writeLines(newLines);
    }
    
