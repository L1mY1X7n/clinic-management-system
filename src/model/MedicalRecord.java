    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String patientId = jTextField6.getText().trim();
        String temperature = jTextField7.getText().trim();
        String bloodPressure = jTextField8.getText().trim();
        String heartRate = jTextField9.getText().trim();
        String notes = jTextArea1.getText().trim().replace(",", ";"); // protect the comma format

        if (patientId.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Patient ID is required.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        try {
            Double.parseDouble(temperature);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Temperature must be a number (e.g. 37.0).", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (!bloodPressure.matches("\\d+/\\d+")) {
            JOptionPane.showMessageDialog(this, "Blood Pressure must look like 120/80.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        try {
            Integer.parseInt(heartRate);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Heart Rate must be a whole number (e.g. 75).", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        updateOrCreateRecord(patientId, temperature, bloodPressure, heartRate, notes);
        JOptionPane.showMessageDialog(this, "Medical record saved successfully.");
    // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

